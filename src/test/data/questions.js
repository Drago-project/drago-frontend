export function option(value, icon = emoji[value] || null) {
  return { value, label: value, icon };
}

export function choice(
  id,
  domain,
  skill,
  difficulty,
  prompt,
  choices,
  correctAnswer,
  spokenPrompt = "",
) {
  return {
    id,
    type: "choice",
    domain,
    skill,
    difficulty,
    prompt,
    choices,
    correctAnswer,
    spokenPrompt,
  };
}

export function imageChoice(
  id,
  domain,
  skill,
  difficulty,
  prompt,
  choices,
  correctAnswer,
  spokenPrompt = "",
) {
  return {
    id,
    type: "imageChoice",
    domain,
    skill,
    difficulty,
    prompt,
    choices,
    correctAnswer,
    spokenPrompt,
  };
}

export function timed(id, skill, prompt, stimuli, expectedCount, idealTimeMs) {
  return {
    id,
    type: "timedNaming",
    domain: "rapidNaming",
    skill,
    difficulty: 2,
    prompt,
    stimuli,
    expectedCount,
    idealTimeMs,
  };
}

export function speechReading(
  id,
  domain,
  skill,
  difficulty,
  prompt,
  expectedWords,
  idealTimeMs,
) {
  return {
    id,
    type: "speechReading",
    domain,
    skill,
    difficulty,
    prompt,
    expectedWords,
    idealTimeMs,
  };
}

